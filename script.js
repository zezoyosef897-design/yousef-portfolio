// --- Language Toggle functionality ---
const langToggleBtn = document.getElementById('lang-toggle');
const htmlElement = document.documentElement;

const savedLang = localStorage.getItem('language');
if (savedLang) {
    setLanguage(savedLang);
} else {
    setLanguage('en');
}

langToggleBtn.addEventListener('click', () => {
    const currentLang = htmlElement.getAttribute('lang');
    const newLang = currentLang === 'en' ? 'ar' : 'en';
    setLanguage(newLang);
});

function setLanguage(lang) {
    htmlElement.setAttribute('lang', lang);
    htmlElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
    localStorage.setItem('language', lang);
    
    // Update Toggle Button Text
    langToggleBtn.textContent = lang === 'en' ? 'AR' : 'EN';
    
    // Translate all regular elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    // Translate placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (translations[lang] && translations[lang][key]) {
            el.setAttribute('placeholder', translations[lang][key]);
        }
    });

    // Re-render dynamic projects for new language
    if (typeof renderProjects === 'function') {
        renderProjects();
    }
}

// --- Theme Toggle functionality ---
const themeToggleBtn = document.getElementById('theme-toggle');

const savedTheme = localStorage.getItem('theme');
if (savedTheme) {
    htmlElement.setAttribute('data-theme', savedTheme);
    updateThemeIcon(savedTheme);
} else {
    htmlElement.setAttribute('data-theme', 'dark');
    updateThemeIcon('dark');
}

themeToggleBtn.addEventListener('click', () => {
    const currentTheme = htmlElement.getAttribute('data-theme');
    const newTheme = currentTheme === 'dark' ? 'light' : 'dark';
    
    htmlElement.setAttribute('data-theme', newTheme);
    localStorage.setItem('theme', newTheme);
    
    updateThemeIcon(newTheme);
});

function updateThemeIcon(theme) {
    if (theme === 'dark') {
        themeToggleBtn.innerHTML = '<i class="fas fa-sun"></i>';
    } else {
        themeToggleBtn.innerHTML = '<i class="fas fa-moon"></i>';
    }
}

// --- Dynamic Projects Fetching ---
let allProjects = [];

async function fetchProjects() {
    try {
        const res = await fetch('/api/projects');
        allProjects = await res.json();
        renderProjects();
    } catch (err) {
        console.error("Failed to fetch projects", err);
    }
}

function renderProjects() {
    const grid = document.getElementById('dynamic-projects-grid');
    if (!grid) return;
    
    const currentLang = htmlElement.getAttribute('lang') || 'en';
    grid.innerHTML = '';
    
    allProjects.forEach((p, index) => {
        const title = currentLang === 'ar' ? p.title_ar : p.title_en;
        const category = currentLang === 'ar' ? p.category_ar : p.category_en;
        const desc = currentLang === 'ar' ? p.desc_ar : p.desc_en;
        const toolsHtml = p.tools ? p.tools.split(',').map(t => `<span>${t.trim()}</span>`).join('') : '';
        
        grid.innerHTML += `
            <div class="project-card fade-in visible" style="transition-delay: ${index * 0.1}s">
                <div class="project-img">
                    <img src="${p.image}" alt="${title}">
                    <div class="project-overlay">
                        <a href="#" class="view-btn"><i class="fas fa-eye"></i></a>
                    </div>
                </div>
                <div class="project-info">
                    <span class="project-category">${category}</span>
                    <h3>${title}</h3>
                    <p>${desc}</p>
                    <div class="project-tools">
                        ${toolsHtml}
                    </div>
                </div>
            </div>
        `;
    });
}

// Call fetch on load
fetchProjects();

// --- Mobile Navigation ---
const menuToggle = document.querySelector('.menu-toggle');
const navLinks = document.querySelector('.nav-links');
const navItems = document.querySelectorAll('.nav-links a');

menuToggle.addEventListener('click', () => {
    navLinks.classList.toggle('active');
    const icon = menuToggle.querySelector('i');
    if (navLinks.classList.contains('active')) {
        icon.classList.remove('fa-bars');
        icon.classList.add('fa-times');
    } else {
        icon.classList.remove('fa-times');
        icon.classList.add('fa-bars');
    }
});

